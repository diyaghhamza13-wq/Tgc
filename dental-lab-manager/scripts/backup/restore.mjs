#!/usr/bin/env node
/**
 * Builds the restore SQL for a DECRYPTED Dental Lab Manager backup.
 *
 *   age -d -i <private-key-file> <backup>.json.age > backup.json
 *   node scripts/backup/restore.mjs backup.json [manifest.json] > restore.sql
 *   psql "$DB_URL" -v ON_ERROR_STOP=1 -f restore.sql
 *   (then delete backup.json and restore.sql)
 *
 * The SQL runs in ONE transaction and:
 *   1. refuses to run unless the target's migration history equals the
 *      backup's (restore into the same schema version: roll back newer
 *      migrations first);
 *   2. disables user triggers on all public tables (no audit / history /
 *      notification side effects), empties them and re-inserts every row in
 *      foreign-key order (identity values kept); the cases <-> stages cycle is
 *      broken by inserting cases.current_stage_id afterwards;
 *   3. resets identity sequences and re-enables the triggers.
 * It touches only schema `public`. Auth accounts and storage files are not
 * restored (they are not in the backup); employees must still exist in Auth.
 *
 * WARNING: this is a FULL restore: rows created after the backup are removed.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';

const [file, manifestFile] = process.argv.slice(2);
if (!file) {
  console.error('usage: restore.mjs backup.json [manifest.json] > restore.sql');
  process.exit(2);
}
const b = JSON.parse(fs.readFileSync(file, 'utf8'));
if (b.format !== 'dlm-backup-v1') throw new Error('not a dlm-backup-v1 file');
const tables = b.tables_in_snapshot;

// integrity: recompute checksums (and compare with the manifest when given)
const sums = Object.fromEntries(tables.map((t) => [t, crypto.createHash('sha256').update(JSON.stringify(b.data[t])).digest('hex')]));
if (manifestFile) {
  const m = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  for (const t of tables) {
    if (m.tables[t]?.sha256 !== sums[t] || m.tables[t]?.rows !== b.data[t].length) throw new Error(`checksum mismatch for table ${t}`);
  }
  console.error(`manifest verified: ${tables.length} tables`);
}

// insert order from the foreign-key graph (public -> public only)
const strip = (n) => n.replace(/^public\./, '').replace(/"/g, '');
const fks = b.schema.fks.filter((f) => !f.parent.includes('.') || f.parent.startsWith('public.'))
  .map((f) => ({ child: strip(f.child), parent: strip(f.parent), columns: f.columns }))
  .filter((f) => f.child !== f.parent && tables.includes(f.parent));
const cols = b.schema.columns;
const deferred = {}; // table -> columns inserted as NULL then updated
const order = [];
const left = new Set(tables);
while (left.size) {
  const ready = [...left].filter((t) => fks.every((f) => f.child !== t || !left.has(f.parent) || (deferred[t] ?? []).some((c) => f.columns.includes(c))));
  if (ready.length) {
    ready.sort().forEach((t) => { order.push(t); left.delete(t); });
    continue;
  }
  // cycle: defer a nullable FK column (not shared with other keys) on an edge
  // whose parent depends back on its child
  const blocking = (f) => left.has(f.child) && left.has(f.parent) && !(deferred[f.child] ?? []).some((c) => f.columns.includes(c));
  const reaches = (from, to, seen = new Set()) => {
    if (from === to) return true;
    if (seen.has(from)) return false;
    seen.add(from);
    return fks.some((f) => blocking(f) && f.child === from && reaches(f.parent, to, seen));
  };
  const freeCol = (f) => f.columns.find((c) => !['lab_id', 'case_id', 'id'].includes(c) && cols[f.child].find((x) => x.name === c)?.nullable);
  const cand = fks.find((f) => blocking(f) && freeCol(f) && reaches(f.parent, f.child));
  if (!cand) throw new Error('unbreakable foreign-key cycle');
  (deferred[cand.child] ??= []).push(freeCol(cand));
}

let tag = 'dlm';
const all = JSON.stringify(b.data);
while (all.includes(`$${tag}$`)) tag += crypto.randomBytes(2).toString('hex');
const lit = (v) => `$${tag}$${JSON.stringify(v)}$${tag}$::jsonb`;
const q = (t) => `public."${t}"`;
const out = [];
out.push('-- Dental Lab Manager restore — generated by scripts/backup/restore.mjs');
out.push(`-- backup exported_at ${b.exported_at}; ${tables.length} tables`);
out.push('begin;');
out.push(`do $guard$ begin
  if (select coalesce(jsonb_agg(version order by version), '[]'::jsonb) from supabase_migrations.schema_migrations)
     <> '${JSON.stringify(b.migrations).replace(/'/g, "''")}'::jsonb then
    raise exception 'migration history differs from the backup: restore into the same schema version';
  end if;
end $guard$;`);
for (const t of tables) out.push(`alter table ${q(t)} disable trigger user;`);
out.push(`truncate table ${tables.map(q).join(', ')};`);
for (const t of order) {
  const rows = b.data[t];
  if (!rows.length) continue;
  const def = deferred[t] ?? [];
  const insRows = def.length ? rows.map((r) => ({ ...r, ...Object.fromEntries(def.map((c) => [c, null])) })) : rows;
  const identity = cols[t].some((c) => c.identity) ? ' overriding system value' : '';
  out.push(`insert into ${q(t)}${identity} select * from jsonb_populate_recordset(null::${q(t)}, ${lit(insRows)});`);
}
for (const [t, dcols] of Object.entries(deferred)) {
  const rows = b.data[t].filter((r) => dcols.some((c) => r[c] !== null)).map((r) => ({ id: r.id, ...Object.fromEntries(dcols.map((c) => [c, r[c]])) }));
  if (rows.length) out.push(`update ${q(t)} t set ${dcols.map((c) => `"${c}" = s."${c}"`).join(', ')} from jsonb_populate_recordset(null::${q(t)}, ${lit(rows)}) s where t.id = s.id;`);
}
for (const t of tables) {
  for (const c of cols[t].filter((x) => x.identity)) {
    out.push(`select setval(pg_get_serial_sequence('public.${t}', '${c.name}'), coalesce((select max("${c.name}") from ${q(t)}), 0) + 1, false);`);
  }
}
for (const t of tables) out.push(`alter table ${q(t)} enable trigger user;`);
out.push('commit;');
process.stdout.write(out.join('\n') + '\n');
console.error(`restore SQL generated: ${order.length} tables, deferred columns: ${JSON.stringify(deferred)}`);
